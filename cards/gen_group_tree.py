"""Generate docs/GROUP_TREE.md from the data, typing no group or series name.

Why this exists: I mis-built fixtures repeatedly by assuming a group name (`Liella!`,
`\u03bc's`, `Aqours`) was a value in a card's `unit` field. It is not. Those are
SERIES-level groups. The consequences are structural, not cosmetic:

  * no unit is called after a group;
  * `\u03bc's` is spelled two ways in the corpus (`lily white` / `lilywhite`);
  * a unit can itself be two groups (`Aqours/SaintSnow`);
  * four units (A-RISE, AiScReam, SaintSnow, SunnyPassion) have no series at all;
  * **Duo/Trio cards carry a NEWLINE-JOINED `series`**, which `map_series_to_group`'s
    exact `match` cannot resolve \u2014 it falls through to `""`. Those cards match through
    `card_series_matches_group` or the card-name branch of `card_matches_group_str`.

Every string below is read out of cards.json, and the Rust test pins the table against
`card_matches_group_str` itself rather than against this script.
"""
import io
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(r"C:\Users\trios\OneDrive\Documents\rabuka_reloaded")
raw = json.load(io.open(ROOT / "cards" / "cards.json", encoding="utf-8"))

# The engine's mapping, transcribed from core/card.rs::map_series_to_group and keyed by
# the exact strings the data contains (found by inspecting them, not by typing them).
ENGINE = {
    "ラブライブ！": "μ's",
    "ラブライブ！サンシャイン!!": "Aqours",
    "ラブライブ！虹ヶ咲学園スクールアイドル同好会": "虹ヶ咲",
    "ラブライブ！スーパースター!!": "Liella!",
    "ラブライブ！蓮ノ空女学院スクールアイドルクラブ": "蓮ノ空",
    "蓮ノ空女学院スクールアイドルクラブ": "蓮ノ空",
}

single = defaultdict(Counter)     # series -> Counter(unit)
joined = Counter()               # the newline-joined multi-series forms
unit_only = Counter()            # units on cards with no series at all
examples = {}

for no, c in raw.items():
    s, u = c.get("series"), c.get("unit")
    if s and "\n" in s:
        joined[s] += 1
        continue
    if s is None:
        if u:
            unit_only[u] += 1
        continue
    single[s][u] += 1
    if (s, u) not in examples and c.get("type") == "メンバー":
        examples[(s, u)] = no

md = [
    "# The group tree",
    "",
    "GENERATED by `cards/gen_group_tree.py` \u2014 regenerate after a re-scrape. Every string here",
    "is read out of `cards/cards.json`; none is typed by hand.",
    "",
    "## The one thing to internalise",
    "",
    "`map_series_to_group` in `engine/src/core/card.rs` maps a card's **`series`** to a",
    "group. **No `unit` is named after a group.** The group names that appear in card",
    "text \u2014 `\u03bc's`, `Liella!`, `Aqours`, `\u8679\u30f6\u5cbd`, `\u83b2\u30cc\u7a7a` \u2014 are resolved against the series.",
    "The names in the `units` column are the subunit names that live in a card's `unit`",
    "field, and they are what a fixture that says \"a `BiBi` member\" should reach for.",
    "",
    "## series \u2192 group \u2192 units",
    "",
    "| group | series | units (with a member card number each) |",
    "|---|---|---|",
]
for s in sorted(single, key=lambda x: ENGINE.get(x, "\uffff")):
    g = ENGINE.get(s, "(UNMAPPED)")
    cells = []
    for u, n in single[s].most_common():
        ex = examples.get((s, u), "")
        label = f"`{u}` ({n})" + (f" \u2014 `{ex}`" if ex else "")
        cells.append(label)
    md.append(f"| **{g}** | `{s}` | " + ", ".join(cells) + " |")

md += [
    "",
    "## Units with NO series",
    "",
    "These cannot be reached by any series lookup. A fixture naming one of these is",
    "matching on `unit` alone.",
    "",
    "| unit | cards |",
    "|---|---|",
]
for u, n in unit_only.most_common():
    md.append(f"| `{u}` | {n} |")

md += [
    "",
    "## Duo / Trio cards: `series` is a newline-joined LIST",
    "",
    "Multi-character cards do not name one series. `series` holds two or more joined by",
    "`\\n`, and `map_series_to_group` matches exactly, so it returns `\"\"` for these and",
    "they fall through to `card_series_matches_group` / the card-name branch of",
    "`card_matches_group_str`. A fixture that asserts a group on a Duo card is exercising",
    "a different code path from a single-character card, which is worth knowing when a",
    "group assertion passes on one and fails on the other.",
    "",
    "| joined series | cards |",
    "|---|---|",
]
for s, n in joined.most_common():
    parts = s.split("\n")
    md.append(f"| " + " + ".join(f"`{p}`" for p in parts) + f" | {n} |")

md += [
    "",
    "## What to do instead of guessing",
    "",
    "1. Read the card's own `unit` and `series` (`cards.json`), or call",
    "   `card_matches_group_str` \u2014 the engine's matcher is the only authority, and",
    "   `assert_card_in_group` already routes through it.",
    "2. Never assert a group by comparing `unit` to the group name yourself.",
    "3. For a subgroup (\u300c\u300eBiBi\u300d\u306e\u30e1\u30f3\u30d0\u30fc\u300d), pick a card whose `unit` IS `BiBi`.",
    "4. For a series group (\u300c\u300e\u03bc's\u300d\u306e\u30ab\u30fc\u30c9\u300d), any card from that series qualifies, `unit` or not.",
    "",
]
out = ROOT / "docs" / "GROUP_TREE.md"
out.write_text("\n".join(md), encoding="utf-8")
print(f"wrote {out.name}")
print(f"  single-series forms : {len(single)}")
print(f"  joined-series forms : {len(joined)}")
print(f"  unit-only groups    : {len(unit_only)}")
for s in sorted(single, key=lambda x: ENGINE.get(x, "\uffff")):
    print(f"    {ENGINE.get(s, '(UNMAPPED)'):<8} <- {s}   units={sorted(u for u in single[s] if u)}")
