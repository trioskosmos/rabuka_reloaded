def get_rare(card_no):
    """Extract rarity from card number."""
    match = re.search(r"-([A-Z0-9＋\-]+)$", card_no)
    if match:
        return match.group(1).replace("＋", "+")
    return ""


def get_series(card_no):
    """Determine series from card number prefix."""
    if card_no.startswith("PL!S-"):
        return "ラブライブ！サンシャイン!!"
    elif card_no.startswith("PL!N-"):
        return "ラブライブ！虹ヶ咲学園スクールアイドル同好会"
    elif card_no.startswith("PL!SP-"):
        return "ラブライブ！スーパースター!!"
    elif card_no.startswith("LL-"):
        return "共通"
    return ""


def download_image(url, dest):
    """Download image from URL."""
    if dest.exists():
        return True
    try:
        req = urllib.request.Request(
            url,
            headers={
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
            },
        )
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = resp.read()
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
            return True
    except Exception as e:
        print(f"  Failed to download {url}: {e}")
        return False


def convert_to_webp(png_path, webp_path):
    """Convert PNG to WebP."""
    if webp_path.exists():
        return True
    try:
        from PIL import Image

        img = Image.open(png_path)
        img.save(webp_path, "WEBP", quality=90)
        return True
    except Exception as e:
        print(f"  Failed to convert {png_path}: {e}")
        return False


def build_entry(card_no, name, card_type, ability, product, expansion):
    """Build a cards.json entry."""
    series = get_series(card_no)
    rare = get_rare(card_no)

    entry = {
        "card_no": card_no,
        "img": f"https://llofficial-cardgame.com/wordpress/wp-content/images/cardlist/{expansion}/{card_no}.png",
        "name": name,
        "product": product,
        "type": card_type,
        "series": series,
        "rare": rare,
        "faq": [],
        "rare_list": [{"card_no": card_no, "name": name}],
        "_img": f"img/cards/{expansion}/{card_no}.png",
    }

    if ability:
        entry["ability"] = ability

    if card_type == "メンバー":
        entry["cost"] = 0
        entry["base_heart"] = {}
        entry["blade"] = 0
    elif card_type == "ライブ":
        entry["score"] = 0
        entry["need_heart"] = {}

    return entry


def main():
    print("=" * 60)
    print("Processing new BP07 and NSD02 cards")
    print("=" * 60)

    # Load existing
    if CARDS_JSON.exists():
        existing = json.loads(CARDS_JSON.read_text(encoding="utf-8"))
        print(f"Loaded {len(existing)} existing cards")
    else:
        existing = {}

    new_count = 0
    skip_count = 0

    for card_data in BP07_CARDS + NSD02_CARDS:
        card_no, name, card_type, ability, product, expansion = card_data

        if card_no in existing:
            skip_count += 1
            continue

        # Build entry
        entry = build_entry(card_no, name, card_type, ability, product, expansion)
        existing[card_no] = entry
        new_count += 1

        # Download image
        img_url = f"https://llofficial-cardgame.com/wordpress/wp-content/images/cardlist/{expansion}/{card_no}.png"
        local_img = CARDS_DIR / "images" / expansion / f"{card_no}.png"
        download_image(img_url, local_img)

        # Convert to webp
        webp_path = WEBP_DIR / f"{card_no}.webp"
        if local_img.exists():
            convert_to_webp(local_img, webp_path)

        print(f"  Added: {card_no} - {name}")

    # Save
    sorted_cards = dict(sorted(existing.items()))
    CARDS_JSON.write_text(
        json.dumps(sorted_cards, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    print(f"\n{'=' * 60}")
    print(f"New cards added: {new_count}")
    print(f"Skipped (existing): {skip_count}")
    print(f"Total cards: {len(sorted_cards)}")
    print("Done!")


if __name__ == "__main__":
    main()
