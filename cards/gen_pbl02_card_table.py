"""Generate a Rust data-integrity test over every PBLL02 card.

Almost every entry in the untested-variants list is the `-R` printing of a card whose
`-PP` sibling has a full suite: the ABILITY is covered, but nothing names the card. The
`PL!SP-pb2-000-DUO` case in docs \u00a78.15 is the same shape, and the failure mode I initially
suspected -- a card silently dropping off a shared node -- would be invisible to 91
separate suites.

One generated table asserts the property for all 172 PBLL02 card numbers at once: the
card exists in the engine, and it carries exactly the ability triggers the printed text
implies. A card that loses its ability, or gains a spurious one, turns this red.
"""
import io
import json
from pathlib import Path

ROOT = Path(r"C:\Users\trios\OneDrive\Documents\rabuka_reloaded")
d = json.load(io.open(ROOT / "cards" / "abilities.json", encoding="utf-8"))
cards = json.load(io.open(ROOT / "cards" / "cards.json", encoding="utf-8"))

# card number -> sorted list of "trigger:action"
# The engine formats the action with Rust's `Debug` (PascalCase), while the JSON uses
# snake_case. Emit PascalCase so the generated table compares against what the test
# actually builds at runtime.
def pascal(action: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in action.split("_") if p)


per_card = {}
for a in d["unique_abilities"]:
    trig = (a.get("triggers") or "").strip()
    act = pascal(((a.get("effect") or {}).get("action")) or "?")
    for c in a.get("cards") or []:
        no = c.split("|")[0].strip()
        per_card.setdefault(no, set()).add(f"{trig} => {act}")

rows = []
for no in sorted(k for k in cards if "-pb2-" in k):
    name = (cards[no].get("name") or "").replace('"', "'")
    abil = sorted(per_card.get(no, ()))
    rows.append((no, name, abil))

body = []
for no, name, abil in rows:
    if not abil:
        body.append(f'    ("{no}", "{name}", &[]),')
    else:
        joined = ", ".join(f'"{a}"' for a in abil)
        body.append(f'    ("{no}", "{name}", &[{joined}]),')

out = f'''//! Every PBLL02 card carries the abilities its printed text implies.
//!
//! GENERATED by `cards/gen_pbl02_card_table.py` \u2014 regenerate after a re-extraction rather
//! than editing by hand; a hand-edit is exactly how a snapshot test rots.
//!
//! # Why this exists
//!
//! `test_inventory.py` reports ability-node coverage, and separately reports the PBLL02
//! card VARIANTS that no test file names (docs \u00a78.15). That list was 91 long, and almost
//! every entry was the `-R` printing of a card whose `-PP` sibling has a full suite: the
//! ability is covered, the card is simply never named.
//!
//! Writing 91 suites to fix that would be busywork. The property that actually matters is
//! one line per card \u2014 "this card exists, and it carries exactly these triggers" \u2014 and it
//! also catches the inverse failure, which is worse: a card that silently DROPS off an
//! ability node shared with a sibling. In that case the sibling's suite still passes, the
//! ability count does not change, and the card behaves as a plain card with no ability at
//! all. Nothing else in the suite can see it.
//!
//! The expectation is compared as a SET of "trigger => action" strings, sorted, so adding
//! an ability to a card is a deliberate, visible change.

use crate::helpers::*;

/// (card number, name, the trigger => action pairs the card must carry)
const EXPECTED: &[(&str, &str, &[&str])] = &[
{chr(10).join(body)}
];

#[test]
fn every_pbl02_card_carries_the_abilities_its_text_implies() {{
    let db = load_real_database();
    let game = TestGame::new(db);

    assert_eq!(
        EXPECTED.len(),
        172,
        "the table should cover every PBLL02 card number; if an expansion import changed \\
         the count, regenerate it rather than editing the number here"
    );

    let mut problems: Vec<String> = Vec::new();
    for (card_no, name, expected) in EXPECTED {{
        let Some(id) = game.db.get_card_id(card_no) else {{
            problems.push(format!("{{card_no}} ({{name}}): not in the database"));
            continue;
        }};
        let card = game.db.get_card(id).expect("looked up above");
        let mut actual: Vec<String> = card
            .resolved_abilities()
            .map(|a| {{
                let trig = a.triggers.as_deref().unwrap_or("").trim().to_string();
                let act = a
                    .effect
                    .as_deref()
                    .map(|e| format!("{{:?}}", e.action))
                    .unwrap_or_else(|| "?".to_string());
                format!("{{trig}} => {{act}}")
            }})
            .collect();
        actual.sort();
        let mut want: Vec<String> = expected.iter().map(|s| s.to_string()).collect();
        want.sort();
        if actual != want {{
            problems.push(format!(
                "{{card_no}} ({{name}}):\\n      expected {{want:?}}\\n      actual   {{actual:?}}"
            ));
        }}
    }}
    assert!(
        problems.is_empty(),
        "{{}} card(s) do not match the generated table:\\n{{}}",
        problems.len(),
        problems.join("\\n")
    );
}}
'''

dest = ROOT / "engine" / "tests" / "test_modules" / "expansion" / "pbl02_card_table_test.rs"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text(out, encoding="utf-8")
print(f"wrote {dest} with {len(rows)} cards")
