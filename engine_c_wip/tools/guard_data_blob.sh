#!/bin/sh
# tools/guard_data_blob.sh - REFUSE to install a card-data blob that is not the
# canonical one.
#
# WHY THIS EXISTS
# ---------------
# `make data` used to run `cp -f cards/build/abilities_strings.bin src/` and
# TRUST whatever was on disk. It was not: cards/build/abilities_strings.bin was
# observed at 726649 bytes against a canonical 726831, and a plain `make` copied
# that truncated blob straight over the good copy in src/ without a word.
#
# ⚠ 2026-10-04: 726649 AND 726831 ARE BOTH HISTORICAL. The canonical pair was
# 726671 bytes / sha256 32fa1a69c0ba9bc2 after the layer-3 regen, and the pin
# that guards it lives in the Makefile (STRINGS_BYTES / STRINGS_SHA256, passed in
# as arguments below) -- this script holds no pin of its own and must not grow one.
# THE HAZARD IS THE PIN, NOT THIS SCRIPT: correcting that pin while gen_data.c
# still held stale offsets would have manufactured a byte splice. Always run
# `bash tools/regen_all.sh` FIRST and move the pin in the same change.
# tests/test_artifacts_consistent.c section 6 independently fails if the
# committed tables and the blob they index come from different generator runs.
#
# Because the interned string pool is UNSEPARATED, a truncated table is NOT a
# build error. It is a silent byte splice of two neighbouring entries:
#
#     cost_limit          -> cost_limitc
#     left_side           -> eft_side
#     invalidate_ability  -> stiming_conditioni
#     resource_type       -> ent_orderchoi
#
# i.e. wrong card data that only shows up as a behavioural mystery much later.
# tools/verify_artifacts.py catches it, but only if somebody remembers to run it
# and nothing has copied over the good blob in the meantime. This guard makes the
# COPY ITSELF refuse.
#
# WHAT IT DOES
# ------------
#   1. the source must exist;
#   2. its byte count must equal the canonical count;
#   3. its sha256 must start with the canonical digest;
#   4. if the destination already exists, source and destination must be the
#      SAME blob (identical size AND identical sha256) - this is the check that
#      turns "copy whatever is there" into "verify, then copy".
#
# It VERIFIES; it never repairs. A blob that fails here has to be regenerated by
# `bash tools/regen_all.sh` as ONE ordered run (cards/build AND the committed C
# tables together, gen_data.c's RBKA_STRINGS_TABLE_LEN being the recorded
# length). Never hand-patch it, never copy part of it.
#
# usage:  guard_data_blob.sh [--install] <source> <dest> <expected-bytes> <expected-sha256>
#
#   --install  after the source passes verification, copy it into place through
#              a temp name + rename. Without it the script only verifies, which
#              is what a build gate wants and what `make data` no longer does:
#              the copy used to be a separate `cp -f` recipe that make SKIPPED
#              whenever src/ looked newer than cards/build/, so a tree already
#              holding a spliced table reported "nothing to be done" while
#              cards/build/ sat there holding a different blob.
#
# exit 0 = safe (and installed, with --install).  exit 1 = refused (loudly).
# exit 64 = bad usage.

set -u

DO_INSTALL=0
if [ "${1:-}" = "--install" ]; then
    DO_INSTALL=1
    shift
fi

if [ $# -ne 4 ]; then
    echo "usage: guard_data_blob.sh [--install] <source> <dest> <expected-bytes> <expected-sha256>" >&2
    exit 64
fi

src=$1
dst=$2
want_bytes=$3
want_sha=$4

# Printed by fail() whatever stage it is called from; `set -u` turns a read of an
# unassigned one into a shell error that truncates the very message the operator
# needs, so they start out assigned.
src_bytes=?
src_sha=?
dst_bytes=(absent)
dst_sha=(absent)

# ── pick a sha256 implementation ─────────────────────────────────────────────
# No fallback to "assume it is fine": if this machine cannot hash a file, the
# build stops. That is the entire point of the guard.
SHA_FLAVOUR=""
if command -v sha256sum >/dev/null 2>&1; then
    SHA_FLAVOUR=coreutils
elif command -v shasum >/dev/null 2>&1; then
    SHA_FLAVOUR=perl
elif command -v openssl >/dev/null 2>&1; then
    SHA_FLAVOUR=openssl
elif command -v python3 >/dev/null 2>&1; then
    SHA_FLAVOUR=python
elif command -v python >/dev/null 2>&1; then
    SHA_FLAVOUR=python
fi

sha256_of() {
    # WINDOWS PATH HAZARD, measured 2026-10-03: with an ABSOLUTE path, MSYS
    # sha256sum emits
    #     \6225b9b5...  C:\\Users\\...\\blob
    # i.e. it prefixes the hash with a BACKSLASH and marks the file as binary with
    # `*`. `cut -d' ' -f1` therefore yields "\6225b9b5..." - leading backslash and
    # all - which matches no expected digest, so the guard REFUSES A PERFECTLY GOOD
    # BLOB the moment anyone passes an absolute path (e.g.
    # `make data STRINGS_BIN=C:\...`). That fails SAFE (a stray backslash can only
    # cause a mismatch, never a false match), but it breaks the build.
    #
    # Extract the 64 hex characters themselves rather than a whitespace field, so
    # the leading `\`, the binary `*` marker and any separator all stop mattering.
    case "$SHA_FLAVOUR" in
        coreutils) sha256sum "$1" | sed -n 's/^[^0-9a-fA-F]*\([0-9a-fA-F]\{64\}\).*/\1/p' ;;
        perl)      shasum -a 256 "$1" | sed -n 's/^[^0-9a-fA-F]*\([0-9a-fA-F]\{64\}\).*/\1/p' ;;
        openssl)   openssl dgst -sha256 "$1" | sed 's/.*= *//' ;;
        python)
            "${PYTHON:-python3}" -c \
                'import hashlib,sys
with open(sys.argv[1],"rb") as fh:
    sys.stdout.write(hashlib.sha256(fh.read()).hexdigest())' "$1"
            ;;
        *) return 127 ;;
    esac
}

size_of() {
    wc -c < "$1" | tr -d ' \t\n\r'
}

fail() {
    {
        echo
        echo "================================================================"
        echo "DATA GUARD: REFUSING TO INSTALL $src"
        echo "================================================================"
        echo "$1"
        echo
        echo "  source        $src"
        echo "  source bytes  $src_bytes"
        echo "  source sha256 $src_sha"
        if [ -f "$dst" ]; then
            echo "  dest          $dst"
            echo "  dest bytes    $dst_bytes"
            echo "  dest sha256   $dst_sha"
        else
            echo "  dest          $dst (absent)"
        fi
        echo "  expected      $want_bytes bytes, sha256 $want_sha..."
        echo
        echo "This blob is NOT the one src/core/generated/gen_data.c was"
        echo "compiled against. Copying it would BYTE-SPLICE the interned"
        echo "string table: entries stop at their neighbours and every card"
        echo "with an ability silently reads the wrong text. There is no"
        echo "build error - that is what makes it dangerous."
        echo
        echo "FIX: bash tools/regen_all.sh"
        echo "     (regenerates cards/build AND the committed C tables in one"
        echo "      ordered run - never one without the other)"
        echo "DO NOT hand-patch the blob and DO NOT copy it in anyway."
        echo "================================================================"
        echo
    } >&2
    exit 1
}

if [ -z "$SHA_FLAVOUR" ]; then
    echo "DATA GUARD: no sha256 tool found (need one of sha256sum, shasum," >&2
    echo "            openssl, python3). Refusing to install $src unverified." >&2
    exit 1
fi

[ -f "$src" ] || fail "the source blob does not exist."
src_bytes=$(size_of "$src")
src_sha=$(sha256_of "$src")
# Measure the destination up front so a refusal report always states what the
# destination actually holds, not that it is "(absent)" by default.
if [ -f "$dst" ]; then
    dst_bytes=$(size_of "$dst")
    dst_sha=$(sha256_of "$dst")
fi

if [ "$src_bytes" != "$want_bytes" ]; then
    fail "the source blob is $src_bytes bytes, not the canonical $want_bytes."
fi

case "$src_sha" in
    "$want_sha"*) : ;;
    *) fail "the source blob's sha256 does not start with $want_sha - it is not the canonical artifact." ;;
esac

# ── the destination ───────────────────────────────────────────────────────
# The source is now pinned to one exact artifact, so the destination is either
# that same artifact or wrong. If it is wrong the copy is a REPAIR, not a
# hazard, so it proceeds -- loudly. Refusing there would leave a tree that had
# already been damaged permanently unrecoverable through `make data`, and
# silence is what let the damage happen in the first place.
if [ ! -f "$dst" ]; then
    echo "data guard: $dst is absent; the verified ${src_bytes}-byte blob will be installed."
    NEED_COPY=1
elif [ "$dst_sha" = "$src_sha" ]; then
    echo "data guard: $src == $dst (${src_bytes} bytes, sha256 ${src_sha}), already installed."
    NEED_COPY=0
else
    echo "data guard: REPAIRING $dst." >&2
    echo "  it held $dst_bytes bytes, sha256 $dst_sha" >&2
    echo "  it is being replaced by the canonical ${src_bytes}-byte blob," >&2
    echo "  sha256 ${src_sha}" >&2
    echo "  (a non-canonical src/ copy IS a byte-spliced ability string" >&2
    echo "   table; re-run: python3 tools/verify_artifacts.py)" >&2
    NEED_COPY=1
fi

if [ "$DO_INSTALL" != 1 ] || [ "$NEED_COPY" != 1 ]; then
    exit 0
fi

# Stage beside the destination and rename, so the destination is never observed
# holding a half-written blob. (Verified BEFORE this point, never after.)
cp -f "$src" "$dst.tmp"
mv -f "$dst.tmp" "$dst"
echo "data guard: installed $dst (${src_bytes} bytes)."
exit 0
