#!/usr/bin/env python3
"""Extract the data tables the C engine needs from abilities_gen.rs.

Emits src/core/generated/gen_data.c with:
  - RBKA_NUM_ABILITIES
  - RBKA_OFFSET_DELTAS[]   (u16, per-ability bytecode slice lengths)
  - RBKA_STRINGS_OFFSETS[] (u32, byte offsets into abilities_strings.bin)
  - RBKA_STRINGS_TABLE_LEN (u32) + RBKA_STRINGS_FNV[] (u32)

WHY THE FNV TABLE EXISTS
------------------------
`abilities_strings.bin` is a *gitignored* build artifact, but the offsets that
index it (RBKA_STRINGS_OFFSETS) are a *committed* C file. The two were allowed
to drift apart, and on 2026-09-30 they did: another agent rebuilt the .bin and
the committed offsets were left pointing 227 slots off, up to 311 bytes wrong.
Because the interned string pool is UNSEPARATED, the resulting byte splices
were silent -- `cost_limit` decoded as `cost_limitc`, `left_side` as `eft_side`.
156 of 6032 strings decoded with a U+FFFD and 105 identifier keys decoded as
splices of two neighbours. Note the pool's *total length* was unchanged, so a
length check alone would NOT have caught it.

So this script now also emits an FNV-1a digest of every interned string, and
rb_verify_generated_tables() in src/ability/vm.c recomputes those digests from
the blob actually loaded at runtime. If anyone ever regenerates the .bin without
regenerating this file, the engine now fails loudly instead of decoding
garbage. Use tools/regen_all.sh, which runs the whole chain in order.

NOTE: src/core card.c uses functions defined in engine/src/core/card.rs
(CardType, CardDatabase, HeartMap, Ability::has_trigger, Ability::triggerless_text,
Card::short_label, etc.). When card.rs is updated, the corresponding C
implementations in card.c must be updated manually — this script only handles
the bytecode/string tables from abilities_gen.rs, not card.rs logic.
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else \
    ROOT / "cards" / "build" / "abilities_gen.rs"
STRINGS_BIN = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else \
    ROOT / "cards" / "build" / "abilities_strings.bin"
GEN_DIR = pathlib.Path(__file__).resolve().parents[1] / "src" / "core" / "generated"
OUT = GEN_DIR / "gen_data.c"
HDR = GEN_DIR / "gen_data.h"


def fnv1a(data: bytes) -> int:
    """FNV-1a 32. Must match rb_fnv1a32() in src/ability/vm.c exactly."""
    h = 0x811C9DC5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def grab_array(text, name):
    # tolerate the `&[T] = &[ ... ];` form (skip the type param)
    m = re.search(name + r":\s*.*?=\s*&\[(.*?)\]\s*;", text, re.S)
    if not m:
        raise SystemExit(f"could not find {name}")
    inner = m.group(1)
    nums = re.findall(r"(\d+)", inner)
    return [int(x) for x in nums]


text = SRC.read_text(encoding="utf-8", errors="replace")

m = re.search(r"NUM_ABILITIES:\s*\w+\s*=\s*(\d+)", text)
if not m:
    raise SystemExit("could not find NUM_ABILITIES")
num_ab = int(m.group(1))

offsets = grab_array(text, r"OFFSET_DELTAS")
str_off = grab_array(text, r"STRINGS_OFFSETS")
pairs = grab_array(text, r"CARD_ABILITY_PAIRS")
assert len(offsets) == num_ab, f"OFFSET_DELTAS len {len(offsets)} != {num_ab}"
assert len(str_off) >= 2, "STRINGS_OFFSETS too short"
assert len(pairs) % 2 == 0, "CARD_ABILITY_PAIRS must be even"

# ── The string table itself. Refuse to emit offsets we cannot vouch for: this
# is the exact pair that was allowed to drift on 2026-09-30.
if not STRINGS_BIN.exists():
    raise SystemExit(
        f"string table missing: {STRINGS_BIN}\n"
        "Run tools/regen_all.sh, or cards/compile_abilities.py first.")
table = STRINGS_BIN.read_bytes()
n_str = len(str_off) - 1
if str_off[-1] != len(table):
    raise SystemExit(
        f"SKEW REFUSED: {SRC.name} says the table is {str_off[-1]} bytes but "
        f"{STRINGS_BIN.name} is {len(table)} bytes. The .rs and the .bin are "
        "from different generator runs. Re-run tools/regen_all.sh.")
if str_off[0] != 0:
    raise SystemExit(f"SKEW REFUSED: STRINGS_OFFSETS[0] = {str_off[0]}, expected 0")
for i in range(len(str_off) - 1):
    if str_off[i] > str_off[i + 1]:
        raise SystemExit(
            f"SKEW REFUSED: STRINGS_OFFSETS not monotonic at index {i} "
            f"({str_off[i]} > {str_off[i+1]})")
fnv = [fnv1a(table[str_off[i]:str_off[i + 1]]) for i in range(n_str)]

lines = []
lines.append("/* Generated by tools/gen_from_rs.py — do not edit. */")
lines.append("#include \"rabuka.h\"")
lines.append("")
lines.append(f"#define RBKA_NUM_STRING_OFFSETS {len(str_off)}")
lines.append(f"const uint32_t RBKA_NUM_ABILITIES = {num_ab};")
lines.append("")
lines.append(f"const uint16_t RBKA_OFFSET_DELTAS[{num_ab}] = {{")
# chunk the u16 list
for i in range(0, len(offsets), 16):
    lines.append("  " + ",".join(str(x) for x in offsets[i:i+16]) + ",")
lines.append("};")
lines.append("")
lines.append(f"const uint32_t RBKA_STRINGS_OFFSETS[{len(str_off)}] = {{")
for i in range(0, len(str_off), 12):
    lines.append("  " + ",".join(str(x) for x in str_off[i:i+12]) + ",")
lines.append("};")
lines.append("")
lines.append("/* Total length of the abilities_strings.bin these offsets index. */")
lines.append(f"const uint32_t RBKA_STRINGS_TABLE_LEN = {len(table)};")
lines.append("")
lines.append("/* FNV-1a of the WHOLE table as a single byte run. One comparison")
lines.append("   that catches ANY byte-level drift, including drift that leaves")
lines.append("   every individual string length unchanged -- which is exactly what")
lines.append("   a mid-pool splice produces, and which a length check cannot see.")
lines.append("   Checked by rb_verify_generated_tables() and")
lines.append("   tools/verify_artifacts.py. */")
lines.append(f"const uint32_t RBKA_STRINGS_TABLE_FNV = {fnv1a(table)}u;")
lines.append("")
lines.append("/* FNV-1a of each interned string's bytes. rb_verify_generated_tables()")
lines.append("   recomputes these from the blob loaded at runtime, so a regenerated")
lines.append("   .bin paired with these stale offsets is a loud failure, not a")
lines.append("   silent byte splice. Keep in lockstep with RBKA_STRINGS_OFFSETS. */")
lines.append(f"const uint32_t RBKA_STRINGS_FNV[{n_str}] = {{")
for i in range(0, len(fnv), 10):
    lines.append("  " + ",".join(str(x) for x in fnv[i:i+10]) + ",")
lines.append("};")
lines.append("")
lines.append(f"#define RBKA_NUM_CARD_ABILITY_PAIRS {len(pairs)//2}")
lines.append(f"const uint16_t RBKA_CARD_ABILITY_PAIRS[{len(pairs)}] = {{")
for i in range(0, len(pairs), 16):
    lines.append("  " + ",".join(str(x) for x in pairs[i:i+16]) + ",")
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines), encoding="utf-8")

hdr = [
    "/* Generated by tools/gen_from_rs.py — do not edit. */",
    "#ifndef RBKA_GEN_DATA_H",
    "#define RBKA_GEN_DATA_H",
    f"#define RBKA_NUM_STRING_OFFSETS {len(str_off)}",
    f"#define RBKA_NUM_ABILITIES_C {num_ab}",
    f"#define RBKA_NUM_CARD_ABILITY_PAIRS {len(pairs)//2}",
    "/* Self-check entry point, defined in src/ability/vm.c. See the comment",
    "   there for what it validates and why it exists. */",
    "int rb_verify_generated_tables(int *out_bad_strings, int *out_bad_keys,",
    "                              char *msg, unsigned long msg_sz);",
    "#endif",
    "",
]
HDR.write_text("\n".join(hdr), encoding="utf-8")
print(f"wrote {OUT} (+{HDR})  NUM_ABILITIES={num_ab}  STRINGS_OFFSETS={len(str_off)}  "
      f"TABLE_LEN={len(table)}  CARD_ABILITY_PAIRS={len(pairs)//2}  bytecode slices sum={sum(offsets)}")
