def glyph_bytes(rows):
    out = []
    for r in rows:
        b = 0
        for c in range(8):
            b = (b << 1) | (1 if c < len(r) and r[c] == '#' else 0)
        out.append(b)
    return out

header = []
header.append("/* Generated by gen_font.py — do not edit. 8x8 4bpp font for VDP text. */")
header.append("#ifndef RABUKA_GENESIS_FONT_H")
header.append("#define RABUKA_GENESIS_FONT_H")
header.append("")
header.append("/* One tile = 8 rows x 4 bytes (32 px, 4bpp). Stored top-to-bottom. */")
header.append("#define FONT_HEIGHT 8")
header.append("#define FONT_FIRST 0x20")
header.append("#define FONT_LAST  0x7E")
header.append("static const unsigned char genesis_font[][32] = {")
for code in range(0x20, 0x7F):
    ch = chr(code)
    rows = ART.get(ch)
    if rows is None:
        # fallback: filled box
        rows = [" ###### ", " ##  ## ", " ##  ## ", " ##  ## ", " ##  ## ", " ##  ## ", " ###### ", "        "]
    b = glyph_bytes(rows)
    # pack 8 rows (4 bytes each) into 32 bytes
    packed = []
    for i in range(0, 8, 1):
        nb0 = b[i]  # a full row of 8 pixels as one byte? we need 4bpp: 2 px per byte
        # convert 8 pixels (bits) to 4 bytes (nibbles)
        pixels = [(nb0 >> (7 - k)) & 1 for k in range(8)]
        nib = [0xF if p else 0x0 for p in pixels]
        packed.append((nib[0] << 4) | nib[1])
        packed.append((nib[2] << 4) | nib[3])
        packed.append((nib[4] << 4) | nib[5])
        packed.append((nib[6] << 4) | nib[7])
    hexes = ", ".join("0x%02X" % x for x in packed)
    header.append("    { %s }, /* '%s' */" % (hexes, ch if ch != '\\' else '\\\\'))
header.append("};")
header.append("#endif")
header.append("")

out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vdp_font.h")
with open(out_path, "w") as f:
    f.write("\n".join(header))
print("wrote", out_path, "glyphs", len(range(0x20, 0x7F)))
