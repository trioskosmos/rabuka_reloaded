use psp::sys;

include!("sjis_table.rs");
include!("cjk_font.rs");

/// Helper: create a null-terminated byte string for PSP syscalls.
/// Stack-allocated, no heap.
fn cstr(s: &[u8]) -> [u8; 128] {
    let mut buf = [0u8; 128];
    let len = s.len().min(127);
    buf[..len].copy_from_slice(&s[..len]);
    buf
}

pub const WIDTH: u32 = 480;
pub const HEIGHT: u32 = 272;
pub const BUF_WIDTH: u32 = 512;

const FONT_W: i32 = 8;
const FONT_H: i32 = 16;

// Font glyph cache buffer (used by sceFont, must live for program duration)
static mut FONT_CACHE: [u8; 65536] = [0u8; 65536];

pub struct Display {
    front: &'static mut [u32],
    back: &'static mut [u32],
    cursor_x: i32,
    cursor_y: i32,
    font: u32,
    line_height: i32,
    use_bitmap: bool,
}

impl Display {
    pub fn new() -> Self {
        let vram_base = unsafe { sys::sceGeEdramGetAddr() as u32 };
        let buf_size = (BUF_WIDTH * HEIGHT) as usize;
        let front_buf = unsafe {
            core::slice::from_raw_parts_mut((0x4000_0000 | vram_base) as *mut u32, buf_size)
        };
        let back_offset = vram_base + (BUF_WIDTH * HEIGHT * 4);
        let back_buf = unsafe {
            core::slice::from_raw_parts_mut((0x4000_0000 | back_offset) as *mut u32, buf_size)
        };

        unsafe {
            sys::sceDisplaySetMode(sys::DisplayMode::Lcd, 480, 272);
            sys::sceDisplaySetFrameBuf(
                front_buf.as_ptr() as *const u8,
                BUF_WIDTH as usize,
                sys::DisplayPixelFormat::Psm8888,
                sys::DisplaySetBufSync::NextFrame,
            );
        }

        let line_height = FONT_H + 2;

        // Initialize sceLibFont and load the Japanese font (jpn0.pgf) directly
        // from flash0:. This works on all CFW PSPs (JP/US/EU) because CFW
        // mounts the flash filesystem. Falls back to system font registry index
        // lookup, then to the embedded bitmap font for non-JP hardware.
        let mut font = 0u32;
        let mut use_bitmap = true;
        let mut error = sys::SceFontErrorCode::Success;
        let params = sys::SceFontNewLibParams {
            user_data_addr: 0,
            num_fonts: 2,
            cache_data: unsafe { FONT_CACHE.as_mut_ptr() as u32 },
            alloc_func: None,
            free_func: None,
            open_func: None,
            close_func: None,
            read_func: None,
            seek_func: None,
            error_func: None,
            io_finish_func: None,
        };
        let font_lib = unsafe { sys::sceFontNewLib(&params, &mut error) };
        if font_lib != 0 {
            // 1) Try sceFontOpenUserFile — works on all CFW PSPs with flash0: mounted.
            let jpn_path = cstr(b"flash0:/font/jpn0.pgf");
            let mut f = unsafe {
                sys::sceFontOpenUserFile(font_lib, jpn_path.as_ptr() as *const u8, 0, &mut error)
            };

            // 2) Try system font registry (index 1 = jpn0 on JP PSPs, may fail on US/EU).
            if f == 0 {
                f = unsafe { sys::sceFontOpen(font_lib, 1, 0, &mut error) };
            }

            // 3) Try Latin font as last resort (index 0 = ltn0).
            if f == 0 {
                f = unsafe { sys::sceFontOpen(font_lib, 0, 0, &mut error) };
            }

            if f != 0 {
                font = f;
                use_bitmap = false;
            }
        }

        let mut disp = Display {
            front: front_buf,
            back: back_buf,
            cursor_x: 0,
            cursor_y: 0,
            font,
            line_height,
            use_bitmap,
        };

        disp.clear();
        disp.swap_buffers();
        disp.clear();
        disp
    }

    pub fn clear(&mut self) {
        for pixel in self.back.iter_mut() {
            *pixel = 0;
        }
        self.cursor_x = 0;
        self.cursor_y = 0;
    }

    pub fn print(&mut self, text: &str) {
        for ch in text.chars() {
            if ch == '\n' {
                self.cursor_y += self.line_height;
                self.cursor_x = 0;
                if self.cursor_y >= HEIGHT as i32 {
                    self.scroll();
                }
                continue;
            }
            self.draw_glyph_at(ch, self.cursor_x, self.cursor_y);
        }
    }

    pub fn println(&mut self, text: &str) {
        self.print(text);
        self.cursor_y += self.line_height;
        self.cursor_x = 0;
        if self.cursor_y >= HEIGHT as i32 {
            self.scroll();
        }
    }

    pub fn write_at(&mut self, row: u32, col: u32, text: &str) {
        let x = col as i32;
        let y = row as i32;
        for ch in text.chars() {
            self.draw_glyph_at(ch, x, y);
        }
    }

    pub fn clear_line(&mut self, row: u32) {
        let y = row as usize;
        let h = self.line_height as usize;
        if y + h > HEIGHT as usize {
            return;
        }
        let row_start = y * BUF_WIDTH as usize;
        let row_end = (y + h) * BUF_WIDTH as usize;
        for pixel in &mut self.back[row_start..row_end] {
            *pixel = 0;
        }
    }

    pub fn draw_menu(&mut self, items: &[&str], selected: usize, title: &str) {
        self.clear();
        self.println(title);
        let dash_count = (WIDTH / FONT_W as u32) as usize;
        let dashes = alloc::vec!['-'; dash_count];
        let separator: alloc::string::String = dashes.into_iter().collect();
        self.println(&separator);

        for (i, item) in items.iter().enumerate() {
            let prefix = if i == selected { " >" } else { "  " };
            let line = alloc::format!("{prefix} {item}");
            self.println(&line);
        }
        self.println("");
        self.println("  D-Pad: navigate  X: select  O: back");
    }

    pub fn swap_buffers(&mut self) {
        unsafe {
            sys::sceDisplaySetFrameBuf(
                self.back.as_ptr() as *const u8,
                BUF_WIDTH as usize,
                sys::DisplayPixelFormat::Psm8888,
                sys::DisplaySetBufSync::NextFrame,
            );
        }
        core::mem::swap(&mut self.front, &mut self.back);
    }

    fn draw_glyph_at(&mut self, ch: char, x: i32, y: i32) {
        if self.use_bitmap {
            self.draw_bitmap_glyph(ch, x, y);
            return;
        }

        // Convert Unicode to Shift-JIS for JP font compatibility.
        let char_code = if ch.is_ascii() {
            ch as u32
        } else {
            match unicode_to_sjis(ch) {
                Some(sjis) => sjis as u32,
                None => {
                    self.draw_bitmap_glyph(ch, x, y);
                    return;
                }
            }
        };

        let mut char_info = sys::SceFontCharInfo::default();
        let ret = unsafe { sys::sceFontGetCharInfo(self.font, char_code, &mut char_info) };
        if ret != 0 {
            self.draw_bitmap_glyph(ch, x, y);
            return;
        }

        let bw = char_info.bitmap_width as usize;
        let bh = char_info.bitmap_height as usize;
        if bw == 0 || bh == 0 {
            self.draw_bitmap_glyph(ch, x, y);
            return;
        }

        let mut buf = alloc::vec![0u8; bw * bh];

        let mut glyph = sys::SceFontGlyphImage {
            pixel_format: sys::SceFontPixelFormatCode::Format8,
            x_pos_64: 0,
            y_pos_64: 0,
            buf_width: bw as u16,
            buf_height: bh as u16,
            bytes_per_line: bw as u16,
            pad: 0,
            buffer_ptr: buf.as_mut_ptr() as u32,
        };

        let ret = unsafe { sys::sceFontGetCharGlyphImage(self.font, char_code, &mut glyph) };
        if ret != 0 {
            self.cursor_x = x + (char_info.sfp26_advance_h >> 6);
            return;
        }

        let px = x + char_info.bitmap_left as i32;
        let py = y + (char_info.bitmap_top as i32 - char_info.sfp26_ascender as i32);

        for gy in 0..bh {
            let dst_y = py + gy as i32;
            if dst_y < 0 || dst_y >= HEIGHT as i32 {
                continue;
            }
            for gx in 0..bw {
                let dst_x = px + gx as i32;
                if dst_x < 0 || dst_x >= WIDTH as i32 {
                    continue;
                }
                let gray = buf[gy * bw + gx];
                if gray > 0 {
                    let idx = (dst_y as u32 * BUF_WIDTH + dst_x as u32) as usize;
                    let alpha = gray as u32;
                    let c = (alpha << 24) | (alpha << 16) | (alpha << 8) | alpha;
                    self.back[idx] = c;
                }
            }
        }

        self.cursor_x = x + (char_info.sfp26_advance_h >> 6);
        self.cursor_y = y;
    }

    fn draw_bitmap_glyph(&mut self, ch: char, x: i32, y: i32) {
        let code = ch as usize;
        if (0x20..=0x7e).contains(&code) {
            self.render_bmp(&ASCII_BITMAPS[code - 0x20], 8, 16, x, y);
        } else if ch.is_ascii() || code == 0x3000 {
            self.render_bmp(&ASCII_BITMAPS[0], 8, 16, x, y);
        } else if let Some(cjk) = lookup_cjk(code as u32) {
            self.render_bmp(cjk, 16, 16, x, y);
        } else {
            self.render_bmp(&ASCII_BITMAPS[0x3f - 0x20], 8, 16, x, y);
        }
    }

    fn render_bmp(&mut self, glyph: &[u8], width: usize, height: usize, x: i32, y: i32) {
        let white = 0xFF_FF_FF_FFu32;
        let row_bytes = (width + 7) / 8;
        for gy in 0..height {
            let dst_y = y + gy as i32;
            if dst_y < 0 || dst_y >= HEIGHT as i32 {
                continue;
            }
            for gx in 0..width {
                let dst_x = x + gx as i32;
                if dst_x < 0 || dst_x >= WIDTH as i32 {
                    continue;
                }
                let byte_idx = gy * row_bytes + gx / 8;
                let bit_idx = 7 - (gx % 8);
                if (glyph[byte_idx] >> bit_idx) & 1 != 0 {
                    let idx = (dst_y as u32 * BUF_WIDTH + dst_x as u32) as usize;
                    self.back[idx] = white;
                }
            }
        }
        self.cursor_x = x + width as i32;
        self.cursor_y = y;
    }

    fn scroll(&mut self) {
        let lh = self.line_height as usize;
        let copy_rows = HEIGHT as usize / lh;
        if copy_rows < 2 {
            self.clear();
            return;
        }
        let bytes_per_row = BUF_WIDTH as usize * lh;
        let total = bytes_per_row * (copy_rows - 1);
        unsafe {
            core::ptr::copy(
                self.back.as_mut_ptr().add(bytes_per_row),
                self.back.as_mut_ptr(),
                total,
            );
        }
        let clear_start = bytes_per_row * (copy_rows - 1);
        let clear_end = bytes_per_row * copy_rows;
        for pixel in &mut self.back[clear_start..clear_end] {
            *pixel = 0;
        }
        self.cursor_y = ((copy_rows - 1) * lh) as i32;
        self.cursor_x = 0;
    }
}

