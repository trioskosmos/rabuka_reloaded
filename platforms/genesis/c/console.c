static const uint8_t reg_init[0x13] = {
    0x04, 0x74, 0x38, 0x34, 0x06, 0x7A, 0x00, 0x00,
    0x00, 0x00, 0x01, 0x00, 0x81, 0x3C, 0x00, 0x02,
    0x01, 0x00, 0x00
};

static uint16_t grid[ROWS][COLS];
static int cur_x = 0, cur_y = 0;

static void vdp_wait(void) { while (*VDP_STAT16 & 0x0001); }

static void vdp_set_write(unsigned long addr) {
    *VDP_CTRL32 = ((addr >> 14) << 16) | ((addr & 0x3FFF) | 0x4000);
}
static void vdp_set_write_cram(unsigned long addr) {
    *VDP_CTRL32 = ((addr >> 14) << 16) | ((addr & 0x3FFF) | 0xC000);
}

static void write_cell(int x, int y, uint16_t cell) {
    unsigned long a = PLANE_A_VRAM + (unsigned long)(y * PLANE_W + x) * 2u;
    vdp_wait();
    vdp_set_write(a);
    *VDP_DATA = cell;
}

static void upload_font(void) {
    for (int g = 0; g < 128; g++) {
        unsigned long a = (unsigned long)g * 32u;
        vdp_wait();
        vdp_set_write(a);
        for (int r = 0; r < 8; r++) {
            unsigned char b = font8x8_basic[g][r];
            unsigned char rb[4];
            rb[0] = (unsigned char)((((b >> 6) & 1) << 4) | ((b >> 7) & 1));
            rb[1] = (unsigned char)((((b >> 4) & 1) << 4) | ((b >> 5) & 1));
            rb[2] = (unsigned char)((((b >> 2) & 1) << 4) | ((b >> 3) & 1));
            rb[3] = (unsigned char)((((b >> 0) & 1) << 4) | ((b >> 1) & 1));
            *VDP_DATA = (uint16_t)((rb[1] << 8) | rb[0]);
            *VDP_DATA = (uint16_t)((rb[3] << 8) | rb[2]);
        }
    }
}

static void upload_palette(void) {
    static const uint16_t pal[16] = {
        0x0000, /* 0 black */
        0x0EEE, /* 1 white */
        0x00EE, /* 2 cyan */
        0x0E00, /* 3 red */
        0x000E, /* 4 blue */
        0x0E0E, /* 5 magenta */
        0x00E0, /* 6 green */
        0x0EE0, /* 7 yellow */
        0x0AAA, 0x0888, 0x0666, 0x0444, 0x0222, 0x0CCC, 0x0999, 0x0440
    };
    vdp_wait();
    vdp_set_write_cram(0);
    for (int i = 0; i < 16; i++) *VDP_DATA = pal[i];
}

static void redraw_plane(void) {
    for (int y = 0; y < ROWS; y++)
        for (int x = 0; x < COLS; x++)
            write_cell(x, y, grid[y][x]);
}

static void scroll_up(void) {
    memmove(&grid[0][0], &grid[1][0], (ROWS - 1) * COLS * sizeof(uint16_t));
    for (int x = 0; x < COLS; x++) grid[ROWS - 1][x] = 0x20;
    redraw_plane();
}

void console_init(void) {
    volatile uint16_t *ctl = (volatile uint16_t *)0xC00004;
    for (int i = 0; i < 0x13; i++)
        *ctl = (uint16_t)(0x8000 | (i << 8) | reg_init[i]);

    /* clear plane A to spaces */
    for (int y = 0; y < ROWS; y++)
        for (int x = 0; x < COLS; x++)
            grid[y][x] = 0x20;
    redraw_plane();
    upload_font();
    upload_palette();
    cur_x = 0; cur_y = 0;
}

void console_putchar(int c) {
    if (c == '\n') {
        cur_x = 0; cur_y++;
    } else if (c == '\r') {
        cur_x = 0;
    } else if (c == '\b') {
        if (cur_x > 0) cur_x--;
    } else {
        if (cur_x >= COLS) { cur_x = 0; cur_y++; }
        if (cur_y >= ROWS) { scroll_up(); cur_y = ROWS - 1; }
        uint16_t cell = (uint16_t)(c & 0x7F);
        grid[cur_y][cur_x] = cell;
        write_cell(cur_x, cur_y, cell);
        cur_x++;
    }
    if (cur_y >= ROWS) { scroll_up(); cur_y = ROWS - 1; }
}

void __console_out(int c) { console_putchar(c); }

void console_puts(const char *s) {
    while (*s) console_putchar((int)(unsigned char)*s++);
}

void console_printf(const char *fmt, ...) {
    char b[200];
    va_list ap; va_start(ap, fmt);
    vsnprintf(b, sizeof b, fmt, ap);  /* from sys.c (libc) */
    va_end(ap);
    console_puts(b);
}
